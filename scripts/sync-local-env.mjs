/**
 * Writes .env.local from `supabase status` for local Vite.
 * Usage: node scripts/sync-local-env.mjs
 */
import { execSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const envPath = path.join(root, ".env.local");

let statusText;
try {
  statusText = execSync("npx supabase status -o env", {
    cwd: root,
    encoding: "utf8",
    stdio: ["ignore", "pipe", "pipe"],
  });
} catch (e) {
  console.error("Supabase is not running. Start it with: npm run db:start");
  console.error(e.stderr?.toString?.() || e.message);
  process.exit(1);
}

const parsed = Object.fromEntries(
  statusText
    .split(/\r?\n/)
    .map((line) => line.trim())
    .filter((line) => line && !line.startsWith("#") && line.includes("="))
    .map((line) => {
      const i = line.indexOf("=");
      return [line.slice(0, i), line.slice(i + 1).replace(/^"|"$/g, "")];
    })
);

const apiUrl = parsed.API_URL || parsed.SUPABASE_URL || "http://127.0.0.1:54321";
const anonKey = parsed.ANON_KEY || parsed.SUPABASE_ANON_KEY || "";

if (!anonKey) {
  console.error("Could not find ANON_KEY in supabase status output:");
  console.error(statusText);
  process.exit(1);
}

const contents = `# Auto-generated by scripts/sync-local-env.mjs — local Supabase
# Safe to regenerate anytime after: npm run db:start

VITE_SUPABASE_URL=${apiUrl}
VITE_SUPABASE_ANON_KEY=${anonKey}
VITE_SUPABASE_STORAGE_BUCKET=uploads

# Label only (pages/auth.me mapping). Not calling Base44 cloud.
VITE_BASE44_APP_ID=operapp

# Vite app
VITE_APP_URL=http://127.0.0.1:5173
`;

fs.writeFileSync(envPath, contents, "utf8");
console.log(`Wrote ${envPath}`);
console.log(`VITE_SUPABASE_URL=${apiUrl}`);
console.log("Studio: http://127.0.0.1:54323");
console.log("Inbucket (emails): http://127.0.0.1:54324");
