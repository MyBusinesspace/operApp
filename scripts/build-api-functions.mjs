/**
 * Compiles every exported Base44 backend function (base44/functions/<name>/entry.ts)
 * into packages/base44-server/generated/<name>.js.
 *
 * The function sources are never edited: their `npm:@base44/sdk` import is
 * redirected to the Supabase-backed server SDK here, exactly like vite.config.js
 * redirects the browser SDK. Re-export from Base44 and re-run this script.
 *
 * Usage: node scripts/build-api-functions.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import * as esbuild from "esbuild";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");
const functionsDir = path.join(root, "base44", "functions");
const outDir = path.join(root, "packages", "base44-server", "generated");

/** `npm:@base44/sdk@0.8.31` → `@base44/sdk` */
function bareSpecifier(specifier) {
  const withoutPrefix = specifier.slice("npm:".length);
  if (withoutPrefix.startsWith("@")) {
    const [scope, name] = withoutPrefix.split("/");
    return `${scope}/${name.split("@")[0]}`;
  }
  return withoutPrefix.split("@")[0];
}

const denoSpecifiers = {
  name: "deno-npm-specifiers",
  setup(build) {
    build.onResolve({ filter: /^npm:/ }, (args) => {
      const name = bareSpecifier(args.path);
      // The compat SDK sits one level up from generated/.
      if (name === "@base44/sdk") return { path: "../sdk.js", external: true };
      return { path: name, external: true };
    });
  },
};

if (!fs.existsSync(functionsDir)) {
  console.error(`No functions directory at ${functionsDir}`);
  process.exit(1);
}

const names = fs
  .readdirSync(functionsDir, { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .filter((name) => fs.existsSync(path.join(functionsDir, name, "entry.ts")))
  .sort();

fs.rmSync(outDir, { recursive: true, force: true });
fs.mkdirSync(outDir, { recursive: true });

await esbuild.build({
  entryPoints: names.map((name) => ({
    in: path.join(functionsDir, name, "entry.ts"),
    out: name,
  })),
  outdir: outDir,
  bundle: true,
  format: "esm",
  platform: "node",
  target: "node20",
  logLevel: "warning",
  external: ["@supabase/supabase-js"],
  plugins: [denoSpecifiers],
});

const index = [
  "// Auto-generated by scripts/build-api-functions.mjs — do not edit by hand",
  "// Lazily imported so a cold start only compiles the function being called.",
  "export const functionModules = {",
  ...names.map((name) => `  ${JSON.stringify(name)}: () => import("./${name}.js"),`),
  "};",
  "",
].join("\n");

fs.writeFileSync(path.join(outDir, "index.js"), index, "utf8");

console.log(`Bundled ${names.length} Base44 functions → ${path.relative(root, outDir)}`);
